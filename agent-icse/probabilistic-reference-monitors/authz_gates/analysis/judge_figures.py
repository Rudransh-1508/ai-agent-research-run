#!/usr/bin/env python3
"""Paper figures for the multi-judge certification study (pgfplots, rebuilt from data).

Reads the frozen-threshold validations (analysis/judge_validation.py output) and writes, under
paper/figures/:
  judge_thresholds.csv / fig_judge_thresholds.tex
      where each judge's certified (deploy) threshold lands against the copied vendor 0.9,
      labelled with the share of safe main-corpus calls it automates;
  judge_leaks.csv / fig_judge_leaks.tex
      destructive calls auto-allowed (main + held-out) at the certified threshold vs at 0.9.

  python3 analysis/judge_figures.py NAME=artifact/validation_groq_X.json [...]
Colors: reference categorical slots 1-2 (#2a78d6 certified, #eb6834 vendor 0.9), validated
with the dataviz palette checker; the 0.9 bars also carry a hatch for grayscale print.
Stdlib only.
"""
import argparse
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "..", "paper", "figures")
BLUE, ORANGE, INK2 = "2A78D6", "EB6834", "52514E"


def deploy_point(v):
    """The operating point to deploy: worst case over runs if repeats exist, else run 1."""
    return v.get("worst_case_certified") or v.get("certified_operating_point")


def heldout_at_deploy(v):
    return v.get("heldout_at_worst_case_t") or v.get("heldout")


def rows_for(named):
    """Accepts judge_validation.py output, or a plain threshold_recipe.py result (a judge
    with one main-corpus run and no held-out scores: plotted in the threshold figure only)."""
    out = []
    for name, path in named:
        v = json.load(open(path))
        c = deploy_point(v)
        vm, vh = v.get("vendor_0.9") or {}, v.get("heldout_vendor_0.9") or {}
        h = heldout_at_deploy(v) if c else None
        has_heldout = bool(vh)
        out.append({
            "judge": name,
            "certifies": int(bool(c)),
            "t": c["t"] if c else "",
            "safe_auto_pct": round(100 * c["safe_auto_allowed"]) if c else 0,
            "vendor_safe_auto_pct": round(100 * vm.get("safe_auto_allowed", 0)),
            "has_heldout": int(has_heldout),
            # A judge with no certified point automates nothing, so it allows nothing.
            "leak_certified": (h["destr_allowed"] if h else 0) + (c["false_allows"] if c else 0),
            "leak_vendor": vm.get("false_allows", 0) + vh.get("destr_allowed", 0),
            "destr_n": 127 + (vh.get("destr_n") or 0),
        })
    return out


def write_csv(path, rows, cols):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)


def coords(rows):
    return ",".join(r["judge"] for r in rows)


def fig_thresholds(rows):
    names = coords(rows)
    pts = " ".join(f"({r['t']},{r['judge']})" for r in rows if r["certifies"])
    labels = "\n".join(
        f"\\node[anchor=west,font=\\scriptsize] at (axis cs:1.04,{r['judge']}) "
        + (f"{{{r['safe_auto_pct']}\\%}};" if r["certifies"] else "{none};")
        for r in rows)
    return f"""% Generated by analysis/judge_figures.py - do not edit by hand.
\\definecolor{{cert}}{{HTML}}{{{BLUE}}}\\definecolor{{ink2}}{{HTML}}{{{INK2}}}
\\begin{{tikzpicture}}
\\begin{{axis}}[scale only axis, width=0.42\\columnwidth, height={0.42 * len(rows):.2f}cm,
  xmin=0, xmax=1, xtick={{0,0.2,0.4,0.6,0.8,1}}, xlabel={{certified auto-allow threshold $t$}},
  xlabel style={{font=\\footnotesize}},
  symbolic y coords={{{names}}}, ytick={{{names}}}, y dir=reverse, enlarge y limits=0.13,
  ymin={rows[0]['judge']}, ymax={rows[-1]['judge']},
  clip=false, axis line style={{ink2}}, tick style={{ink2}}, ticklabel style={{font=\\footnotesize}},
  xmajorgrids, grid style={{ink2!20}}, axis x line*=bottom, axis y line*=left]
\\draw[ink2, dashed, thick] (axis cs:0.9,{rows[0]['judge']}) ++(0pt,6pt) coordinate (top)
  (axis cs:0.9,{rows[-1]['judge']}) ++(0pt,-6pt) coordinate (bot) (top) -- (bot);
\\node[anchor=south east,font=\\scriptsize,text=ink2,inner sep=1pt] at (top) {{vendor 0.9}};
\\node[above,font=\\scriptsize,anchor=south west,inner sep=1pt] at (axis cs:1.04,{rows[0]['judge']}) [yshift=6pt] {{safe automated}};
\\addplot[only marks, mark=*, mark size=2.4pt, color=cert, mark options={{draw=white, line width=0.6pt}}]
  coordinates {{{pts}}};
{labels}
\\end{{axis}}
\\end{{tikzpicture}}
"""


def fig_leaks(rows):
    rows = [r for r in rows if r["has_heldout"]]
    names = coords(rows)
    n = rows[0]["destr_n"]
    cert = " ".join(f"({r['leak_certified']},{r['judge']})" for r in rows)
    vend = " ".join(f"({r['leak_vendor']},{r['judge']})" for r in rows)
    xmax = max(max(r["leak_vendor"] for r in rows) * 1.15, 6)
    return f"""% Generated by analysis/judge_figures.py - do not edit by hand.
\\definecolor{{cert}}{{HTML}}{{{BLUE}}}\\definecolor{{vend}}{{HTML}}{{{ORANGE}}}\\definecolor{{ink2}}{{HTML}}{{{INK2}}}
\\begin{{tikzpicture}}
\\begin{{axis}}[scale only axis, xbar=1pt, bar width=5pt, width=0.6\\columnwidth,
  height={0.62 * len(rows):.2f}cm, xmin=0, xmax={xmax:.0f},
  xlabel={{destructive calls auto-allowed (of {n})}}, xlabel style={{font=\\footnotesize}},
  symbolic y coords={{{names}}}, ytick={{{names}}}, y dir=reverse, enlarge y limits=0.16,
  ymin={rows[0]['judge']}, ymax={rows[-1]['judge']},
  nodes near coords, nodes near coords style={{font=\\scriptsize, text=black}},
  axis line style={{ink2}}, tick style={{ink2}}, ticklabel style={{font=\\footnotesize}},
  xmajorgrids, grid style={{ink2!20}}, axis x line*=bottom, axis y line*=left,
  legend style={{font=\\scriptsize, draw=none, at={{(0.5,1.03)}}, anchor=south,
  legend columns=2, /tikz/every even column/.append style={{column sep=6pt}}}},
  legend cell align=left]
\\addplot[fill=cert, draw=white] coordinates {{{cert}}};
\\addplot[fill=vend, draw=white, postaction={{pattern=north east lines, pattern color=white}}]
  coordinates {{{vend}}};
\\legend{{certified $t$, copied vendor 0.9}}
\\end{{axis}}
\\end{{tikzpicture}}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("judges", nargs="+", help="NAME=validation.json, in display order")
    ap.add_argument("--outdir", default=FIG)
    args = ap.parse_args()
    named = [j.split("=", 1) for j in args.judges]
    rows = rows_for(named)
    os.makedirs(args.outdir, exist_ok=True)
    cols = list(rows[0])
    write_csv(os.path.join(args.outdir, "judge_thresholds.csv"), rows, cols)
    write_csv(os.path.join(args.outdir, "judge_leaks.csv"), rows, cols)
    with open(os.path.join(args.outdir, "fig_judge_thresholds.tex"), "w") as f:
        f.write(fig_thresholds(rows))
    with open(os.path.join(args.outdir, "fig_judge_leaks.tex"), "w") as f:
        f.write(fig_leaks(rows))
    for r in rows:
        print(r)


if __name__ == "__main__":
    main()
