"""Emit the two new figures as pgfplots source, straight from the JSON artifacts.

  paper/figures/frontier_K.tex   the frontier at K = 2,3,4 for n = 3, showing the
                                 tradeoff steepen, flatten, and vanish at K_flat
  paper/figures/identity.tex     storage (log2 K bits) against accountability
                                 margin for the episode records, which is where
                                 the identity-versus-volume claim becomes visible

Nothing is transcribed: every coordinate is read from frontier_sweep.json and
experiment_episodes.json, so the figures cannot drift from the experiments.
"""
import json, math, os
import sys as _sys, pathlib as _pl
_sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1]))
from c39.paths import data, out

os.makedirs("paper/figures", exist_ok=True)

# ---------------------------------------------------------------- figure 1
fs = json.load(open(data("frontier_sweep.json")))["3"]
kflat = fs["K_flat"]
marks = {"2": "*", "3": "square*", "4": "triangle*"}
lines = [r"% Generated by make_figures2.py -- do not edit by hand.",
         r"\begin{tikzpicture}",
         r"\begin{axis}[",
         r"  width=\columnwidth, height=0.70\columnwidth,",
         r"  xlabel={required margin $\gamma$},",
         r"  ylabel={expected bit errors $D$},",
         r"  xmin=0, xmax=0.72, ymin=0.42, ymax=1.06,",
         r"  legend pos=north west, legend cell align=left,",
         r"  grid=major, grid style={gray!18},",
         r"]"]
for K in sorted(fs["curves"], key=int):
    pts = [(p["gamma"], p["D"]) for p in fs["curves"][K]["points"]
           if p["D"] is not None]
    coords = " ".join(f"({g:.6f},{d:.6f})" for g, d in pts)
    lines += [f"\\addplot[thick, mark={marks.get(K,'o')}] coordinates {{{coords}}};",
              f"\\addlegendentry{{$K={K}$"
              + (r" $=\gamma_2(Q_3)$" if int(K) == kflat else "") + "}"]
lines += [r"\end{axis}", r"\end{tikzpicture}"]
open(out("paper/figures/frontier_K.tex"), "w", newline="\n").write("\n".join(lines) + "\n")
print(f"wrote paper/figures/frontier_K.tex  ({len(fs['curves'])} curves)")

# ---------------------------------------------------------------- figure 2
ep = json.load(open(data("experiment_episodes.json")))
n = "5"
rows = {r["scheme"]: r for r in ep[n]["exact"]}
IDENTITY = {"full_trace", "per_agent_bit", "per_agent_coarse", "recency_k",
            "role_rollup"}
PRETTY = {"full_trace": "full trace", "per_agent_bit": "1 bit/agent",
          "per_agent_coarse": "top-half agents", "recency_k": "recency window",
          "role_rollup": "role rollup", "quality_only": "quality summary",
          "global_summary": "artifact multiset", "aggregate": "count",
          "final_output": "final output"}
lines = [r"% Generated by make_figures2.py -- do not edit by hand.",
         r"\begin{tikzpicture}",
         r"\begin{axis}[",
         r"  width=\columnwidth, height=0.70\columnwidth,",
         r"  xlabel={storage $\log_2 K$ (bits)},",
         r"  ylabel={accountability margin $\gamma$},",
         r"  xmin=0, xmax=8.6, ymin=-0.03, ymax=0.58,",
         r"  legend pos=north west, legend cell align=left,",
         r"  grid=major, grid style={gray!18},",
         r"  nodes near coords, point meta=explicit symbolic,",
         r"  every node near coord/.append style={font=\tiny, anchor=west,"
         r" xshift=2pt},",
         r"]"]
for group, style, label in [
        (True, "mark=*, only marks, mark size=2pt", "keeps agent identity"),
        (False, "mark=square, only marks, mark size=2.2pt", "identity destroyed")]:
    pts = [(r["bits"], r["gamma"], PRETTY.get(k, k))
           for k, r in rows.items() if (k in IDENTITY) == group]
    body = " ".join(f"({b:.4f},{g:.6f}) [{t}]" for b, g, t in sorted(pts))
    lines += [f"\\addplot[{style}] coordinates {{{body}}};",
              f"\\addlegendentry{{{label}}}"]
lines += [r"\end{axis}", r"\end{tikzpicture}"]
open(out("paper/figures/identity.tex"), "w", newline="\n").write("\n".join(lines) + "\n")
print(f"wrote paper/figures/identity.tex  ({len(rows)} records at n={n})")

# ------------------------------------------------- the identity price, for H1
print("\nidentity price (relative margin loss / relative storage saving):")
best_id = max((r for k, r in rows.items() if k in IDENTITY),
              key=lambda r: r["gamma"])
for k, r in sorted(rows.items(), key=lambda kv: -kv[1]["gamma"]):
    if k in IDENTITY or r["gamma"] >= best_id["gamma"]:
        continue
    dm = (best_id["gamma"] - r["gamma"]) / best_id["gamma"]
    ds = (best_id["bits"] - r["bits"]) / best_id["bits"]
    price = dm / ds if ds > 1e-12 else float("inf")
    print(f"  {PRETTY.get(k,k):<18} margin loss {dm:5.1%}  storage saving "
          f"{ds:5.1%}   price {price:5.2f}x")
