"""Emit paper/figures/frontier.tex (pgfplots) from the exact frontier.

No plotting library: the figure is LaTeX source, so it needs no extra
dependency in the pinned environment and typesets in the paper's own fonts.
"""
import math, os
import sys as _sys, pathlib as _pl
_sys.path.insert(0, str(_pl.Path(__file__).resolve().parents[1]))
from c39.paths import data, out

def M_n(n):
    return sum(math.comb(n, k) * min(k, n - k) for k in range(n + 1)) / 2 ** n

def D(n, g):
    return M_n(n) + n * g * ((n - 1) / 2 - M_n(n))

os.makedirs("paper/figures", exist_ok=True)

lines = [
    r"% Generated by make_figures.py -- do not edit by hand.",
    r"% Requires \usepackage{pgfplots} in the preamble.",
    r"\begin{tikzpicture}",
    r"\begin{axis}[",
    r"  width=\columnwidth, height=0.72\columnwidth,",
    r"  xlabel={required unilateral margin $\gamma$},",
    r"  ylabel={$D^\ast(2,\gamma)$ \ (expected bit errors)},",
    r"  xmin=0, xmax=0.35, ymin=0.6, ymax=4.2,",
    r"  legend pos=north west, legend cell align=left,",
    r"  grid=major, grid style={very thin, gray!25},",
    r"  tick label style={font=\footnotesize},",
    r"  label style={font=\small},",
    r"  legend style={font=\footnotesize, draw=gray!40},",
    r"]",
]

for n in (3, 5, 7, 9):
    gmax = 1.0 / n
    pts = " ".join(
        f"({gmax*j/40:.6f},{D(n, gmax*j/40):.6f})" for j in range(41)
    )
    lines.append(rf"\addplot[thick] coordinates {{{pts}}};")
    lines.append(rf"\addlegendentry{{$n={n}$}}")
    # terminal point: the frontier always ends at (1/n, (n-1)/2)
    lines.append(
        rf"\addplot[only marks, mark=*, mark size=1.6pt, forget plot] "
        rf"coordinates {{({gmax:.6f},{(n-1)/2:.6f})}};"
    )

lines += [r"\end{axis}", r"\end{tikzpicture}"]

open(out("paper/figures/frontier.tex"), "w").write("\n".join(lines) + "\n")
print("wrote paper/figures/frontier.tex")

# sanity: the closed form must terminate at ((1/n), (n-1)/2)
for n in (3, 5, 7, 9):
    assert abs(D(n, 1 / n) - (n - 1) / 2) < 1e-12, n
print("endpoint identity D(1/n) = (n-1)/2 verified for n = 3,5,7,9")
