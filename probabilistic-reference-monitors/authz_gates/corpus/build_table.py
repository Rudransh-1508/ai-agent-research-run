#!/usr/bin/env python3
"""Generate CORPUS_TABLE.md from gates.json + manual_extraction.json.

Computes the P1-P4 prediction outcomes (full corpus and pilot/held-out split)
from the recorded per-gate fields. Stdlib only. Every count in the generated
table is reproducible by re-running this script.

Counting rules (fixed here, matching PREREGISTRATION.md):
- P1 unit: one gate. A gate "fails open on at least one failure mode" iff its
  classification is fail-open, or partial with at least one error-path mode
  recorded as letting the action proceed (each partial gate's note documents
  which). Denominator: gates with a determinable error path (all included
  gates here; none were undeterminable).
- P2 unit: one gate's threshold set. "No documented derivation" = provenance
  undocumented or copied-from-vendor-docs. Gates with no threshold constants
  (fx) are excluded from the denominator.
- P3: gates shipping the vendor docs' illustrative threshold (0.9 or 0.5)
  verbatim (vendor refs: docs.typesafe.ai/primitives/noul `noul > 0.9`;
  docs.typesafe.ai/confidence `confidence < 0.5` floor and `confidence > 0.9`;
  accessed 2026-09-21).
- P4: manual check, recorded per gate in cross_evaluation.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))

FAILS_OPEN = {"fail-open", "partial"}
NO_DERIVATION = ("undocumented", "copied-from-vendor-docs")

# Gates shipping a vendor-illustrative 0.9 or 0.5 constant verbatim, with the
# constant's role (provenance in parentheses).
P3_MATCHES = {
    "jev-engineering": "DENY_ABOVE 0.90 on a Noul (copied-from-vendor-docs)",
    "r2r-jev": "DESTRUCTIVE_THRESHOLD 0.90 on a Noul (undocumented)",
    "OpenWork": "coverage/check cutoff 0.9 on Booleans (undocumented)",
    "pi-jev": "blockOn destructive 0.9 (documented-derivation: set above the measured 0.85 benign band)",
    "wakegate": "0.5 unsure/judged split (undocumented; secondary to skipBelow 0.2)",
    "dsh-auto-mode": "safetyThreshold 0.5 and noul split 0.5 (documented-derivation)",
    "jev-use": "REPORTED_CONFIDENCE_THRESHOLD 0.5 (documented-derivation)",
    "jev-commit": "substantive 0.50 (undocumented)",
}


def main():
    gates = {g["name"]: g for g in json.load(open(os.path.join(HERE, "gates.json")))["gates"]}
    manual = json.load(open(os.path.join(HERE, "manual_extraction.json")))
    manual.pop("_schema", None)

    included = [g for g in gates.values() if g["inclusion"] == "included"]
    included.sort(key=lambda g: g["name"].lower())
    missing = [g["name"] for g in included if g["name"] not in manual]
    if missing:
        raise SystemExit(f"missing manual extraction for: {missing}")

    out = []
    out.append("# Corpus table: probabilistic decision-model gates in the agent authorization path\n")
    out.append("Source: yibie/awesome-jev (Verification & Guardrails + decision-gate entries from Agent Decisions, "
               "Infra, Content Moderation). Cloned 2026-09-21, shallow, HEAD pinned below. "
               "Every field was read from the pinned checkout by hand; quotes are verbatim from the named file:line. "
               "Fields that could not be determined are marked 'undetermined'. "
               "Generated by build_table.py from gates.json + manual_extraction.json.\n")

    out.append("## Per-gate extraction\n")
    for g in included:
        m = manual[g["name"]]
        out.append(f"### {g['name']} — {g['url']}")
        out.append(f"- Category: {g['category']} · pilot set: {'yes' if m.get('pilot') else 'no'} · "
                   f"pinned SHA `{g.get('pinned_sha', 'n/a')}` · accessed {g.get('clone_date', '2026-09-21')}")
        out.append(f"- Purpose (awesome-jev): {g['purpose']}")
        out.append(f"- Question(s) asked: {m['questions_asked']}")
        out.append(f"- Primitive(s): {', '.join(m['primitives'])}")
        if m["thresholds"]:
            out.append("- Threshold constant(s):")
            for t in m["thresholds"]:
                out.append(f"    - `{t['value']}` — {t['role']} ({t['ref']}: \"{t['quote']}\")")
        else:
            out.append("- Threshold constant(s): none")
        out.append(f"- Threshold provenance: {m['threshold_provenance']}")
        out.append(f"- Action set: {', '.join(m['action_set'])}")
        a = m["attacker_text_unsanitised"]
        out.append(f"- Attacker-reachable text passed unsanitised: {a['value']} — {a['evidence']}")
        ep = m["error_path"]
        out.append(f"- Error path: timeout={ep['timeout']}, 429={ep['http_429']}, 5xx={ep['http_5xx']}, malformed={ep['malformed_response']}")
        for ev in ep["evidence"]:
            out.append(f"    - {ev['ref']}: \"{ev['quote']}\"")
        if ep.get("note"):
            out.append(f"    - note: {ep['note']}")
        out.append(f"- **Fail classification: {m['fail_classification']}**")
        out.append(f"- Cross-evaluation: {m['cross_evaluation']}")
        if m.get("notes"):
            out.append(f"- Notes: {m['notes']}")
        out.append("")

    # ---- summary / predictions ----
    def split(rows):
        pilot = [r for r in rows if manual[r["name"]].get("pilot")]
        held = [r for r in rows if not manual[r["name"]].get("pilot")]
        return pilot, held

    pilot, held = split(included)

    def p1_count(rows):
        yes = [r["name"] for r in rows if manual[r["name"]]["fail_classification"] in FAILS_OPEN]
        return yes

    def p2_count(rows):
        with_t = [r for r in rows if manual[r["name"]]["thresholds"]]
        no_doc = [r["name"] for r in with_t
                  if any(manual[r["name"]]["threshold_provenance"].startswith(p) for p in NO_DERIVATION)]
        return with_t, no_doc

    out.append("## Summary: registered predictions P1-P4\n")
    out.append(f"Corpus: {len(included)} included gates ({len(pilot)} pilot, {len(held)} held-out). "
               "Excluded after code read: stanley-code (advisory-only, no gate), jev-superpowers (never calls the model itself). "
               "Excluded before cloning: Blink, Yappy, Jev AI, Elvex blog (no public source URL); "
               "keyword-matched non-gates (routers, SDKs, MCP adapters, compaction tools, Discord/Telegram/YouTube moderators). "
               "harshwasan/jev-sentinel does not exist. jev-harness was initially mis-flagged as a scaffold from its list entry and is included after cloning (see CORPUS_NOTES.md).\n")

    for label, rows in (("full corpus", included), ("pilot", pilot), ("held-out", held)):
        p1_yes = p1_count(rows)
        with_t, no_doc = p2_count(rows)
        out.append(f"### {label} (n={len(rows)})")
        out.append(f"- P1 (fail-open >= 50%): {len(p1_yes)}/{len(rows)} = {len(p1_yes)/len(rows):.0%} "
                   f"fail open on at least one of timeout/429/5xx/malformed -> **{'SUPPORTED' if len(p1_yes)/len(rows) >= 0.5 else 'NOT SUPPORTED'}**")
        out.append(f"  - fail-open: {sum(1 for r in rows if manual[r['name']]['fail_classification']=='fail-open')}, "
                   f"partial: {sum(1 for r in rows if manual[r['name']]['fail_classification']=='partial')}, "
                   f"fail-closed: {sum(1 for r in rows if manual[r['name']]['fail_classification']=='fail-closed')}")
        out.append(f"- P2 (>= 60% no documented derivation): {len(no_doc)}/{len(with_t)} gates-with-thresholds "
                   f"= {len(no_doc)/len(with_t):.0%} -> **{'SUPPORTED' if len(no_doc)/len(with_t) >= 0.6 else 'NOT SUPPORTED'}**")
        p3 = [r["name"] for r in rows if r["name"] in P3_MATCHES]
        out.append(f"- P3 (>= 1 gate ships vendor-illustrative 0.9/0.5 verbatim): {len(p3)} gates -> **{'SUPPORTED' if p3 else 'NOT SUPPORTED'}**"
                   + ("".join(f"\n  - {n}: {P3_MATCHES[n]}" for n in p3)))
        out.append("")

    out.append("### P4 (no cross-evaluation)")
    out.append("No gate in the corpus cites a published evaluation against another gate or against a public "
               "benchmark with baselines -> **SUPPORTED (holds)**. Closest calls, checked by hand: "
               "jev-belay's README cites limpet's published self-calibration (AUROC 0.50 on 1,500 stops) as motivation "
               "— a citation of another gate's self-evaluation, not an evaluation against it; "
               "Sniff Test benchmarks Jev against Haiku 4.5/Sonnet/Opus on its own 54-paragraph set (LLM comparison on "
               "private data, not a public benchmark with baselines); jev-engineering's 300-call injection test, "
               "pi-heed's 79-session reruns, Abide's 93-session replay, hermes-jev-approvals' 24-case frozen holdout, "
               "and JevLoop's bench are all single-gate self-evaluations.\n")

    out.append("### Fail classification overview\n")
    out.append("| classification | full corpus | pilot | held-out |")
    out.append("|---|---|---|---|")
    for cls in ("fail-open", "partial", "fail-closed"):
        out.append(f"| {cls} | {sum(1 for r in included if manual[r['name']]['fail_classification']==cls)} "
                   f"| {sum(1 for r in pilot if manual[r['name']]['fail_classification']==cls)} "
                   f"| {sum(1 for r in held if manual[r['name']]['fail_classification']==cls)} |")
    out.append("")
    out.append("Threshold provenance (gates with thresholds; fx has none):")
    for prov in ("documented-derivation", "swept-on-data", "copied-from-vendor-docs", "undocumented"):
        names = [r["name"] for r in included if manual[r["name"]]["thresholds"] and manual[r["name"]]["threshold_provenance"].startswith(prov)]
        out.append(f"- {prov}: {len(names)} — {', '.join(names) if names else '—'}")
    out.append("")

    with open(os.path.join(HERE, "CORPUS_TABLE.md"), "w") as f:
        f.write("\n".join(out))
    print(f"wrote CORPUS_TABLE.md: {len(included)} gates")


if __name__ == "__main__":
    main()
